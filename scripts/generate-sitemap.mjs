// Builds public/sitemap.xml from the routes and the slugs in src/data/services.js and projects.js.
// Runs automatically before `npm run build`. The domain comes from `url` in src/data/site.js.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFile(path.join(root, f), 'utf8');

const site = await read('src/data/site.js');
const domain = site.match(/url:\s*'([^']+)'/)[1].replace(/\/$/, '');
const slugsIn = (src) => [...src.matchAll(/^\s{4}slug:\s*'([^']+)'/gm)].map((m) => m[1]);

const services = slugsIn(await read('src/data/services.js'));
const projects = slugsIn(await read('src/data/projects.js'));

const routes = [
  '/', '/services', '/restaurant-solutions', '/work', '/industries', '/technologies', '/about', '/pricing',
  '/contact', '/privacy-policy', '/cookie-policy',
  ...services.map((s) => `/services/${s}`),
  ...projects.map((p) => `/work/${p}`)
];

const today = new Date().toISOString().slice(0, 10);
const xml = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${routes.map((r) => `  <url><loc>${domain}${r}</loc><lastmod>${today}</lastmod></url>`).join('\n')}
</urlset>
`;
await writeFile(path.join(root, 'public/sitemap.xml'), xml);
await writeFile(
  path.join(root, 'public/robots.txt'),
  `User-agent: *\nAllow: /\n\n# Generated by scripts/generate-sitemap.mjs from the url in src/data/site.js\nSitemap: ${domain}/sitemap.xml\n`
);
console.log(`sitemap.xml: ${routes.length} URLs`);
